    ContactMessageID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FullName VARCHAR(150) NOT NULL,
    Email VARCHAR(255) NOT NULL,
    CompanyName VARCHAR(200) NULL,
    Message TEXT NOT NULL,
    EmailSent BOOLEAN NOT NULL DEFAULT FALSE,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ==========================================
-- DEMO REQUEST
-- One row per submission of the "Request a demo" form.
-- ==========================================
CREATE TABLE IF NOT EXISTS DemoRequest (
    DemoRequestID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FullName VARCHAR(150) NOT NULL,
    Email VARCHAR(255) NOT NULL,
    CompanyName VARCHAR(200) NOT NULL,
    Message TEXT NULL,
    EmailSent BOOLEAN NOT NULL DEFAULT FALSE,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ==========================================
-- AUDIT LOG
-- ==========================================
CREATE TABLE IF NOT EXISTS AuditLog (
    AuditID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrgID INTEGER NOT NULL,
    UserID INTEGER NULL,
    Action VARCHAR(100) NOT NULL,
    Module VARCHAR(100) NOT NULL,
    RecordID INTEGER NULL,
    IPAddress VARCHAR(100),
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT FK_Audit_Organization
        FOREIGN KEY (OrgID) REFERENCES Organization(OrgID),
    CONSTRAINT FK_Audit_User
        FOREIGN KEY (UserID) REFERENCES "user"(UserID)
);
