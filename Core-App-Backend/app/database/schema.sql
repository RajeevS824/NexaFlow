/*
=========================================================
Enterprise Multi-Tenant RBAC Database Schema
Database : PostgreSQL
=========================================================
Safe to run repeatedly: every table is CREATE TABLE IF NOT EXISTS, so missing
tables are created and existing tables and their data are left untouched.

Identifiers are deliberately NOT quoted (so PostgreSQL stores them lower-case
and the CamelCase names used by the application's SQL keep working). The only
quoted name is "user", because USER is a reserved word in PostgreSQL.
*/

-- ==========================================
-- ORGANIZATION
-- ==========================================
CREATE TABLE IF NOT EXISTS Organization (
    OrgID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrganizationName VARCHAR(200) NOT NULL,
    OrganizationSlug VARCHAR(100) UNIQUE,
    CompanyCode VARCHAR(50) UNIQUE,
    Email VARCHAR(255) NOT NULL,
    Address VARCHAR(500),
    Country VARCHAR(100),
    State VARCHAR(100),
    City VARCHAR(100),
    Status BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    UpdatedAt TIMESTAMP NULL
);

-- ==========================================
-- PRODUCT MASTER
-- ==========================================
CREATE TABLE IF NOT EXISTS Product (
    ProductID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductName VARCHAR(150) NOT NULL,
    ProductCode VARCHAR(50) UNIQUE NOT NULL,
    Description TEXT,
    Version VARCHAR(20),
    IsActive BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ==========================================
-- LICENSE
-- One record per purchased product
-- ==========================================
CREATE TABLE IF NOT EXISTS License (
    LicenseID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LicenseKey VARCHAR(200) NOT NULL UNIQUE,
    OrgID INTEGER NOT NULL,
    ProductID INTEGER NOT NULL,
    PurchaseDate DATE NOT NULL,
    ExpiryDate DATE NULL,
    Status BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT FK_License_Organization
        FOREIGN KEY (OrgID) REFERENCES Organization(OrgID),
    CONSTRAINT FK_License_Product
        FOREIGN KEY (ProductID) REFERENCES Product(ProductID),
    CONSTRAINT UQ_License_Product UNIQUE (OrgID, ProductID)
);

-- ==========================================
-- ADMIN
-- ==========================================
CREATE TABLE IF NOT EXISTS Admin (
    AdminID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrgID INTEGER NOT NULL,
    FullName VARCHAR(150) NOT NULL,
    Email VARCHAR(255) NOT NULL UNIQUE,
    PasswordHash VARCHAR(500) NOT NULL,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    UpdatedAt TIMESTAMP NULL,
    CONSTRAINT FK_Admin_Organization
        FOREIGN KEY (OrgID) REFERENCES Organization(OrgID)
);

-- ==========================================
-- USER
-- ("user" is quoted: USER is a reserved word in PostgreSQL)
-- ==========================================
CREATE TABLE IF NOT EXISTS "user" (
    UserID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrgID INTEGER NOT NULL,
    EmployeeCode VARCHAR(50) UNIQUE,
    FirstName VARCHAR(100) NOT NULL,
    Email VARCHAR(255) NOT NULL UNIQUE,
    PasswordHash VARCHAR(500) NOT NULL,
    Status BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    UpdatedAt TIMESTAMP NULL,
    CONSTRAINT FK_User_Organization
        FOREIGN KEY (OrgID) REFERENCES Organization(OrgID)
);

-- ==========================================
-- COMMUNITY EDITION USER
-- Frontend sign-ups land here and can access the workspace
-- without going through the enterprise admin creation flow.
-- IDs start at 90000 so they are easy to tell apart from enterprise
-- Admin/User IDs at a glance (90000, 90001, 90002, ...).
-- ==========================================
CREATE TABLE IF NOT EXISTS CommunityEditionUser (
    CommunityEditionUserID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 90000) PRIMARY KEY,
    OrgID INTEGER NOT NULL,
    FullName VARCHAR(150) NOT NULL,
    Email VARCHAR(255) NOT NULL UNIQUE,
    PasswordHash VARCHAR(500) NOT NULL,
    Status BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    UpdatedAt TIMESTAMP NULL,
    CONSTRAINT FK_CommunityEditionUser_Organization
        FOREIGN KEY (OrgID) REFERENCES Organization(OrgID)
);

-- ==========================================
-- ROLE
-- ==========================================
CREATE TABLE IF NOT EXISTS Role (
    RoleID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrgID INTEGER NOT NULL,
    RoleName VARCHAR(150) NOT NULL,
    Description VARCHAR(500),
    Status BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedBy INTEGER NULL,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    UpdatedAt TIMESTAMP NULL,
    CONSTRAINT FK_Role_Organization
        FOREIGN KEY (OrgID) REFERENCES Organization(OrgID),
    CONSTRAINT FK_Role_Admin
        FOREIGN KEY (CreatedBy) REFERENCES Admin(AdminID)
);

-- ==========================================
-- USER ROLE MAPPING
-- ==========================================
CREATE TABLE IF NOT EXISTS UserRole (
    UserRoleID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID INTEGER NOT NULL,
    RoleID INTEGER NOT NULL,
    AssignedBy INTEGER NULL,
    AssignedDate TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT FK_UserRole_User
        FOREIGN KEY (UserID) REFERENCES "user"(UserID),
    CONSTRAINT FK_UserRole_Role
        FOREIGN KEY (RoleID) REFERENCES Role(RoleID),
    CONSTRAINT FK_UserRole_Admin
        FOREIGN KEY (AssignedBy) REFERENCES Admin(AdminID),
    CONSTRAINT UQ_UserRole UNIQUE (UserID, RoleID)
);

-- ==========================================
-- ROLE PRODUCT ACCESS
-- Role gets access only to products purchased by the organization.
-- ==========================================
CREATE TABLE IF NOT EXISTS RoleProductAccess (
    AccessID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RoleID INTEGER NOT NULL,
    ProductID INTEGER NOT NULL,
    CanView BOOLEAN NOT NULL DEFAULT TRUE,
    CanEdit BOOLEAN NOT NULL DEFAULT FALSE,
    CanExecute BOOLEAN NOT NULL DEFAULT FALSE,
    AssignedBy INTEGER NULL,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT FK_RPA_Role
        FOREIGN KEY (RoleID) REFERENCES Role(RoleID),
    CONSTRAINT FK_RPA_Product
        FOREIGN KEY (ProductID) REFERENCES Product(ProductID),
    CONSTRAINT FK_RPA_Admin
        FOREIGN KEY (AssignedBy) REFERENCES Admin(AdminID),
    CONSTRAINT UQ_Role_Product UNIQUE (RoleID, ProductID)
);

-- ==========================================
-- USER LOGIN SESSION
-- ==========================================
CREATE TABLE IF NOT EXISTS UserSession (
    SessionID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID INTEGER NOT NULL,
    Token TEXT NOT NULL,
    IPAddress VARCHAR(100),
    LoginTime TIMESTAMP NOT NULL DEFAULT NOW(),
    LogoutTime TIMESTAMP NULL,
    IsActive BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_UserSession_User
        FOREIGN KEY (UserID) REFERENCES "user"(UserID)
);

-- ==========================================
-- ADMIN SESSION
-- ==========================================
CREATE TABLE IF NOT EXISTS AdminSession (
    SessionID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AdminID INTEGER NOT NULL,
    Token TEXT NOT NULL,
    IPAddress VARCHAR(100),
    LoginTime TIMESTAMP NOT NULL DEFAULT NOW(),
    LogoutTime TIMESTAMP NULL,
    IsActive BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_AdminSession_Admin
        FOREIGN KEY (AdminID) REFERENCES Admin(AdminID)
);

-- ==========================================
-- PASSWORD RESET TOKEN
-- One row per "forgot password" request. AccountType tells us
-- which table AccountID refers to: 'admin' | 'user' | 'community'.
-- ==========================================
CREATE TABLE IF NOT EXISTS PasswordResetToken (
    TokenID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Token VARCHAR(255) NOT NULL UNIQUE,
    AccountType VARCHAR(20) NOT NULL,
    AccountID INTEGER NOT NULL,
    Email VARCHAR(255) NOT NULL,
    ExpiresAt TIMESTAMP NOT NULL,
    UsedAt TIMESTAMP NULL,
    CreatedAt TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ==========================================
-- DATA CLEANUP: restore Product.IsActive
-- A prior version of the "deactivate product" toggle briefly (and
-- incorrectly) flipped this GLOBAL catalog flag instead of the
-- per-organization License.Status flag. Product.IsActive is meant to mean
-- "this product exists in the catalog" (not "this org has it turned on"),
-- so it belongs back on for every known product. Per-organization
-- enable/disable is License.Status, which this does not touch. Safe to run
-- on every startup - once restored, this is a no-op.
-- ==========================================
UPDATE Product SET IsActive = TRUE WHERE IsActive = FALSE;

-- ==========================================
-- DATA CLEANUP: de-duplicate UserRole
-- A user only ever holds ONE role at a time in this app. This keeps only
-- the most recent role assignment per user. Safe to run on every startup:
-- once cleaned, there is nothing left to delete and it becomes a no-op.
-- ==========================================
DELETE FROM UserRole
WHERE UserRoleID NOT IN (
    SELECT MAX(ur2.UserRoleID)
    FROM UserRole ur2
    GROUP BY ur2.UserID
);

-- ==========================================
